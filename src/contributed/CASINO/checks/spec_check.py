"""spec_check.py <deck dir> : read lapwfn.data and pwfn.data by the text of SPEC version 1
(not by wien2kqmc's reader) and check every field a reader uses: the labels and counts, the
units and frame, the meshes, the inner series, the core and its tail, the G list, the reality
flags, and the normalisation and orthogonality of every band over the primitive cell (spheres
from the radial tables and coefficients, interstitial from pwfn.data with the exact step
function). Written as an independent check of Elk's writer (20 October 2026); carried here
unchanged but for the exit status, which is 1 when a check fails."""
import sys
import numpy as np

D = sys.argv[1]
L = open(D + '/lapwfn.data').read().split('\n')
pos = [0]
fails = []


def fail(msg):
    fails.append(msg)
    print('FAIL', msg)


def nxt():
    s = L[pos[0]]
    pos[0] += 1
    return s


def label(t):
    s = nxt()
    if s.rstrip() != t:
        fail(f'line {pos[0]}: expected label {t!r}, found {s!r}')


def blank():
    s = nxt()
    if s.strip():
        fail(f'line {pos[0]}: expected a blank line, found {s!r}')


def nums(n, typ=float):
    out = []
    while len(out) < n:
        out += [typ(x) for x in nxt().split()]
    if len(out) != n:
        fail(f'line {pos[0]}: {len(out)} numbers where {n} expected')
    return np.array(out)


label('LAPWFN.DATA: LAPW orbitals, format version 1')
label('Title'); nxt(); blank()
label('BASIC INFO'); label('----------')
label('Generated by:'); gen = nxt()
label('Method:'); meth = nxt()
label('DFT functional:'); xc = nxt()
label('Relativistic treatment:'); rel = nxt()
label('Spin polarized:'); spin = nxt()
label('Units:'); units = nxt()
label('Total energy (au per primitive cell)'); etot = float(nxt())
label('Fermi energy (au)'); ef = float(nxt())
label('Number of electrons per primitive cell (core included)'); ne = int(nxt())
label('Number of valence electrons per primitive cell (in the WAVE FUNCTION section)'); nv = int(nxt())
label('Interstitial part:')
label('pwfn.data: same k points and bands in the same order; coefficients multiply exp(i(k+G).r) with no prefactor')
blank()
for a, b in ((meth, 'DFT'), (rel, 'none'), (spin, 'F'), (units, 'hartree, bohr')):
    if a.strip() != b:
        fail(f'BASIC INFO value {a!r} where SPEC has {b!r}')
label('GEOMETRY'); label('--------')
label('Number of atoms per primitive cell'); nat = int(nxt())
label('Atomic number, type, position (au) of each atom')
Z, typ, R = [], [], []
for i in range(nat):
    t = nxt().split()
    Z.append(int(t[0])); typ.append(int(t[1])); R.append([float(x) for x in t[2:5]])
R = np.array(R)
label('Primitive lattice vectors (au)')
A = np.array([[float(x) for x in nxt().split()] for i in range(3)])
blank()
omega = abs(np.linalg.det(A))
B = 2 * np.pi * np.linalg.inv(A).T          # rows: reciprocal vectors
label('ATOM TYPES'); label('----------')
label('Number of atom types'); nt = int(nxt())
T = []
for it in range(nt):
    label('Type, label, atomic number, sphere radius (au), number of mesh points')
    t = nxt().split()
    ty = dict(t=int(t[0]), lab=t[1], Z=float(t[2]), R=float(t[3]), nr=int(t[4]))
    label('Mesh points (au)'); ty['r'] = nums(ty['nr'])
    label('Maximum l of the sphere expansion'); ty['L'] = int(nxt())
    label('Number of radial functions for l = 0 to L'); ty['nl'] = nums(ty['L'] + 1, int)
    ty['f'] = {}
    for l in range(ty['L'] + 1):
        for j in range(ty['nl'][l]):
            label('Radial function: l, j, kind, energy (au)')
            t = nxt().split()
            if int(t[0]) != l or int(t[1]) != j + 1 or t[2] not in ('u', 'udot', 'lo'):
                fail(f'radial function header {t} for l {l} j {j + 1}')
            label('Inner series: join radius, A, c2, c3')
            ser = [float(x) for x in nxt().split()]
            label('Values u(r) on the mesh')
            ty['f'][(l, j)] = (t[2], float(t[3]), ser, nums(ty['nr']))
    T.append(ty)
blank()
label('CORE STATES'); label('-----------')
label('Number of core states of each type'); ncs = nums(nt, int)
cores = []
for it in range(nt):
    for c in range(ncs[it]):
        label('Core state: type, label, n, l, energy (au), occupation, number of mesh points')
        t = nxt().split()
        cs = dict(t=int(t[0]), lab=t[1], n=int(t[2]), l=int(t[3]), E=float(t[4]), occ=int(t[5]), nc=int(t[6]))
        label('Inner series: join radius, A, c2, c3'); cs['ser'] = [float(x) for x in nxt().split()]
        label('Tail beyond the sphere: kappa'); cs['kappa'] = float(nxt())
        label('Mesh points (au)'); cs['r'] = nums(cs['nc'])
        label('Values u(r) on the mesh'); cs['u'] = nums(cs['nc'])
        cores.append(cs)
blank()
label('WAVE FUNCTION'); label('-------------')
label('Number of k-points'); nk = int(nxt())
K = []
for ik in range(nk):
    label('k-point # ; # of bands (up spin/down spin) ; k-point coords (au)')
    t = nxt().split()
    kk = dict(n=int(t[1]), nd=int(t[2]), k=np.array([float(x) for x in t[3:6]]), bands=[])
    if int(t[0]) != ik + 1 or kk['nd'] != 0:
        fail(f'k-point line {t}')
    for ib in range(kk['n']):
        label('Band, spin, eigenvalue (au), real (T/F)')
        t = nxt().split()
        band = dict(E=float(t[2]), real=t[3], c=[])
        if int(t[0]) != ib + 1 or int(t[1]) != 1 or t[3] not in ('T', 'F'):
            fail(f'band line {t}')
        for ia in range(nat):
            label(f'Sphere coefficients of atom {ia + 1}: l, m, then (re, im) for each radial function of that l')
            ty = T[typ[ia] - 1]
            cc = {}
            for l in range(ty['L'] + 1):
                for m in range(-l, l + 1):
                    t = nxt().split()
                    if int(t[0]) != l or int(t[1]) != m or len(t) != 2 + 2 * ty['nl'][l]:
                        fail(f'coefficient line {t[:2]} for l {l} m {m}')
                    v = np.array([float(x) for x in t[2:]])
                    cc[(l, m)] = v[0::2] + 1j * v[1::2]
            band['c'].append(cc)
        kk['bands'].append(band)
    K.append(kk)
rest = [s for s in L[pos[0]:] if s.strip()]
if rest:
    fail(f'{len(rest)} non-blank lines after the last band')

print(f'# {D}: parsed by SPEC 1: {nat} atoms, {nt} types, {len(cores)} core states, {nk} k points; '
      f'N_e {ne}, N_v {nv}; Omega {omega:.10f}; xc {xc.strip()!r}')
for ia in range(nat):
    print(f'  atom {ia + 1}: Z {Z[ia]} type {typ[ia]} ({T[typ[ia] - 1]["lab"]}) at {R[ia]}')
# --- S2 the meshes
for ty in T:
    r = ty['r']
    q = r[1:] / r[:-1]
    print(f'S2 type {ty["lab"]}: n_r {ty["nr"]}, r_1 {r[0]:.6e}, last - R {r[-1] - ty["R"]:+.2e}, ratio {q[0]:.12f}, '
          f'ratio spread {q.max() - q.min():.2e}')
    if abs(r[-1] - ty['R']) > 1e-12 or q.max() - q.min() > 1e-11:
        fail(f'type {ty["lab"]} mesh')
    # S3 the inner series of every valence function; S6a orthonormality of each l over the sphere
    worst = (0, 0, 0)
    for (l, j), (kind, E, ser, u) in ty['f'].items():
        rj, a, c2, c3 = ser
        inside = r <= rj * (1 + 1e-12)
        s = a * r ** l * (1 - ty['Z'] * r / (l + 1) + c2 * r ** 2 + c3 * r ** 3)
        dev = np.max(np.abs(s[inside] - u[inside])) / max(np.max(np.abs(u[inside])), 1e-300)
        if rj > min(0.05, 0.1 * ty['R']) or (l >= 2 and c3 != 0.0) or dev > 1e-13:
            fail(f'type {ty["lab"]} l {l} j {j + 1}: r_j {rj:.3e}, c3 {c3}, table-series {dev:.1e}')
        worst = max(worst, (dev, rj, l))
    print(f'S3 type {ty["lab"]}: inside r_j the table is the series to {worst[0]:.1e} (largest r_j {max(v[2][0] for v in ty["f"].values()):.3e}, bound {min(0.05, 0.1 * ty["R"]):.3e})')

x = None


def rint(r, f):
    """integral of f dr on a logarithmic mesh: Simpson in ln r of f r, the first interval from 0
    by the f ~ r^p power fitted to the first two points"""
    h = np.log(r[1] / r[0])
    g = f * r
    n = len(r) if len(r) % 2 == 1 else len(r) - 1
    s = h / 3 * (g[0] + g[n - 1] + 4 * g[1:n - 1:2].sum() + 2 * g[2:n - 1:2].sum())
    if n != len(r):
        s += 0.5 * h * (g[-2] + g[-1])
    return s


for ty in T:
    r = ty['r']
    worst = 0.0
    for l in range(ty['L'] + 1):
        for j1 in range(ty['nl'][l]):
            for j2 in range(ty['nl'][l]):
                v = rint(r, ty['f'][(l, j1)][3] * ty['f'][(l, j2)][3] * r ** 2)
                worst = max(worst, abs(v - (1.0 if j1 == j2 else 0.0)))
    print(f'S6a type {ty["lab"]}: the radial functions of each l orthonormal over the sphere to {worst:.2e}')
# --- S4 the cores
for cs in cores:
    ty = T[cs['t'] - 1]
    r, u, nr = cs['r'], cs['u'], ty['nr']
    rj, a, c2, c3 = cs['ser']
    same = np.max(np.abs(r[:nr] - ty['r'])) / ty['R']
    q = r[1:] / r[:-1]
    inside = r <= rj * (1 + 1e-12)
    s = a * r ** cs['l'] * (1 - ty['Z'] * r / (cs['l'] + 1) + c2 * r ** 2 + c3 * r ** 3)
    sdev = np.max(np.abs(s[inside] - u[inside])) / np.max(np.abs(u[inside]))
    tail = u[nr - 1] * np.exp(-cs['kappa'] * (r[nr:] - ty['R']))
    tdev = np.max(np.abs(tail - u[nr:])) / np.max(np.abs(u))
    # kappa against the table's own slope at R: a degree-7 polynomial through the last 8 points
    xx = r[nr - 8:nr] - ty['R']
    p = np.polyfit(xx, u[nr - 8:nr], 7)
    kap = -p[-2] / p[-1]
    # and by a cubic fit of ln|u| through the same points, exact for an exponential: the polynomial
    # of u is off by 1.1e-3 for silicon's 1s (kappa 11.85, the function a factor 80 across the
    # eight points, u(R) 5e-12 of its maximum) where this gives 1.1e-4; the test is on this one
    # (fleurqmc, 21 October 2026; the original rule's figure is still printed). The 1.1e-4 is
    # the writer's own: its kappa, -u'/u by a degree-5 polynomial of u in ln r through six points
    # about R, is low by 1.0e-4 for that core (the rule applied to exp(-kappa r) on silicon's mesh
    # gives the same), every other core's within 1e-7; hence the bound of 5e-4 where the original
    # was 1e-4. Nil in effect: u(R) is 5e-12 of the core's maximum.
    qf = np.polyfit(xx, np.log(np.abs(u[nr - 8:nr])), 3)
    kapln = -qf[-2]
    umax = np.max(np.abs(u))
    first_below = abs(u[-1]) < 1e-12 * umax and abs(u[-2]) >= 1e-12 * umax
    norm = rint(r, u ** 2 * r ** 2)
    tailw = u[nr - 1] ** 2 * (ty['R'] ** 2 / (2 * cs['kappa']) + 2 * ty['R'] / (2 * cs['kappa']) ** 2
                              + 2 / (2 * cs['kappa']) ** 3)
    print(f'S4 core {cs["lab"]} of {ty["lab"]}: E {cs["E"]}, occ {cs["occ"]}, n_c {cs["nc"]} (r_end {r[-1]:.3f}); '
          f'first {nr} points the valence mesh to {same:.1e}, ratio spread {q.max() - q.min():.1e}; series inside '
          f'r_j {rj:.3e} to {sdev:.1e}; tail = u(R)exp(-kappa(r-R)) to {tdev:.1e}; kappa {cs["kappa"]:.8f} against '
          f'-u\'/u of the table {kap:.8f} ({kap / cs["kappa"] - 1:+.1e}; by the ln fit {kapln / cs["kappa"] - 1:+.1e}); last value {abs(u[-1]) / umax:.2e} of the '
          f'max, the first below 1e-12: {first_below}; norm to the end of the mesh {norm:.8f}; tail weight beyond R '
          f'(analytic) {tailw:.4e}')
    if same > 1e-12 or q.max() - q.min() > 1e-11 or sdev > 1e-13 or tdev > 1e-13 or abs(kapln / cs['kappa'] - 1) > 5e-4 \
            or not first_below or abs(norm - 1) > 1e-5:
        fail(f'core {cs["lab"]} of {ty["lab"]}')

# --- pwfn.data
P = open(D + '/pwfn.data').read().split('\n')


def after(lab, start=0):
    for i in range(start, len(P)):
        if P[i].strip() == lab:
            return i + 1
    raise SystemExit(f'pwfn.data: no label {lab!r}')


i = after('Number of G-vectors'); ng = int(P[i])
i = after('Gx Gy Gz (au)', i)
G = np.array([[float(x) for x in P[i + j].split()] for j in range(ng)])
nG = G @ A.T / (2 * np.pi)                   # G . a_i / 2 pi, integers for a reciprocal vector
print(f'S5 pwfn.data: {ng} G vectors, the largest |G . a/2pi - nearest integer| {np.max(np.abs(nG - np.rint(nG))):.1e}')
if np.max(np.abs(nG - np.rint(nG))) > 1e-10:
    fail('G list not reciprocal lattice vectors')
i = after('Number of k-points', i); nkp = int(P[i]); i += 1
C = []
for ik in range(nkp):
    i = after('k-point # ; # of bands (up spin/down spin) ; k-point coords (au)', i)
    t = P[i].split(); nb = int(t[1]); kv = np.array([float(x) for x in t[3:6]])
    if nb != K[ik]['n'] or np.max(np.abs(kv - K[ik]['k'])) > 1e-10:
        fail(f'pwfn k point {ik + 1} differs from lapwfn.data')
    cb = []
    for ib in range(nb):
        i = after('Band, spin, eigenvalue (au)', i)
        e = float(P[i].split()[2])
        if abs(e - K[ik]['bands'][ib]['E']) > 1e-12:
            fail(f'eigenvalue k {ik + 1} band {ib + 1}')
        i = after('Eigenvector coefficients', i)
        v = np.array([[float(x) for x in P[i + j].strip().strip('()').split(',')] for j in range(ng)])
        cb.append(v[:, 0] + 1j * v[:, 1])
        i += ng
    C.append(np.array(cb))
print(f'S1 pwfn.data: k points, band counts and eigenvalues agree with lapwfn.data; N_v {nv}')


# --- S6 the norm and the overlaps of the bands over the primitive cell
def j1x(x):
    """j_1(x)/x, with its series at small x"""
    out = np.empty_like(x)
    sm = x < 1e-3
    xs = x[sm]
    out[sm] = 1 / 3 - xs ** 2 / 30 + xs ** 4 / 840
    xl = x[~sm]
    out[~sm] = (np.sin(xl) / xl ** 2 - np.cos(xl) / xl) / xl
    return out


q = G[None, :, :] - G[:, None, :]            # q[G, G'] = G' - G
qn = np.linalg.norm(q, axis=2)
M = omega * np.eye(ng, dtype=complex)
for ia in range(nat):
    Ra = T[typ[ia] - 1]['R']
    M -= 4 * np.pi * Ra ** 3 * j1x(qn * Ra) * np.exp(1j * (q @ R[ia]))
Srad = []
for ty in T:
    r = ty['r']
    S = {}
    for l in range(ty['L'] + 1):
        n = ty['nl'][l]
        S[l] = np.array([[rint(r, ty['f'][(l, a)][3] * ty['f'][(l, b)][3] * r ** 2) for b in range(n)] for a in range(n)])
    Srad.append(S)
for ik, kk in enumerate(K):
    nb = kk['n']
    O = np.zeros((nb, nb), dtype=complex)
    sph = np.zeros(nb)
    for ia in range(nat):
        ty = T[typ[ia] - 1]
        S = Srad[typ[ia] - 1]
        for l in range(ty['L'] + 1):
            for m in range(-l, l + 1):
                X = np.array([kk['bands'][b]['c'][ia][(l, m)] for b in range(nb)])   # nb x n_l
                O += X.conj() @ S[l] @ X.T
    sphd = np.real(np.diag(O)).copy()
    Ci = C[ik]
    O += Ci.conj() @ M @ Ci.T
    dn = np.abs(np.real(np.diag(O)) - 1)
    off = np.abs(O - np.diag(np.diag(O)))
    # the reality flags
    rdev = 0.0
    nreal = 0
    for b in range(nb):
        band = kk['bands'][b]
        if band['real'] != 'T':
            continue
        nreal += 1
        big = max(np.max(np.abs(Ci[b])), max(np.max(np.abs(v)) for cc in band['c'] for v in cc.values()))
        for ia in range(nat):
            ty = T[typ[ia] - 1]
            for l in range(ty['L'] + 1):
                for m in range(-l, l + 1):
                    rdev = max(rdev, np.max(np.abs(band['c'][ia][(l, -m)] - (-1) ** m * np.conj(band['c'][ia][(l, m)]))) / big)
        # pwfn partner c_{-G-2k} = c_G*
        k2 = 2 * kk['k']
        key = {tuple(np.rint(g @ A.T / (2 * np.pi)).astype(int)): j for j, g in enumerate(G)}
        n2 = np.rint(k2 @ A.T / (2 * np.pi)).astype(int)
        for j, g in enumerate(G):
            p = key.get(tuple(-np.rint(g @ A.T / (2 * np.pi)).astype(int) - n2))
            if p is not None:
                rdev = max(rdev, abs(Ci[b][p] - np.conj(Ci[b][j])) / big)
    print(f'S6 k {ik + 1} {kk["k"]}: {nb} bands, {nreal} written real; norm - 1 up to {dn.max():.2e} '
          f'(sphere part {sphd.min():.4f} to {sphd.max():.4f}); largest overlap of two bands {off.max():.2e}; '
          f'real bands meet c(l,-m) = (-1)^m c(l,m)* and c(-G-2k) = c(G)* to {rdev:.1e} of the largest coefficient')
    if dn.max() > 1e-5 or off.max() > 1e-5 or rdev > 1e-8:
        fail(f'k {ik + 1}: normalisation, orthogonality or reality')
print(f'# {len(fails)} failures' + (': ' + '; '.join(fails) if fails else ''))
sys.exit(1 if fails else 0)
