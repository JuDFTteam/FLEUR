MODULE m_gfprep_write
   !Output of gfprep: the layer inp.xml files, the gf_inp template, the
   !layer potentials/densities in gf_pot.hdf/gf_cdn.hdf and the potentials
   !beyond the vacuum embedding planes of a film
#ifdef CPP_MPI
   USE mpi
#endif
   USE m_juDFT
   USE m_constants
   USE m_types_kpts
   USE m_types_forcetheo
   USE m_winpXML
   USE m_gf_types, ONLY: t_embinp
   USE m_gf_iodop, ONLY: gf_wrtdop, gf_wrtcoul, gf_iodop_writevacemb, GF_POTFILE, GF_CDNFILE
   USE m_gfprep_inp, ONLY: t_layergeo
   USE m_gfprep_bulk, ONLY: t_gfprep_struct
   USE m_gfprep_layer, ONLY: t_gfprep_layer
   IMPLICIT NONE
   PRIVATE
   PUBLIC :: gfprep_write_inpxml, gfprep_write_gfinp, gfprep_write_gfen, gfprep_write_potden, gfprep_write_vacemb

CONTAINS

   SUBROUTINE gfprep_write_inpxml(filename, b, lay, kpts)
      CHARACTER(LEN=*), INTENT(IN)      :: filename
      TYPE(t_gfprep_struct), INTENT(IN) :: b
      TYPE(t_gfprep_layer), INTENT(IN)  :: lay
      TYPE(t_kpts), INTENT(IN)          :: kpts

      TYPE(t_forcetheo) :: forcetheo
      TYPE(t_kpts)      :: kptsArray(1)
      CHARACTER(LEN=40) :: kptsSelection(3)

      kptsArray(1) = kpts
      kptsSelection = ""
      kptsSelection(1) = kpts%kptsName
      CALL w_inpXML(lay%atoms, lay%vacuum, lay%input, b%stars, b%fi%sliceplot, forcetheo, b%fi%banddos, &
                    b%fi%dfpt, lay%cell, lay%sym, b%xcpot, lay%noco, b%fi%mpinp, b%fi%hybinp, kptsArray, &
                    kptsSelection, lay%enpara, b%fi%gfinp, b%fi%hub1inp, .FALSE., [.TRUE., .TRUE., .TRUE., .TRUE.], &
                    filename=filename, add_filename="")
   END SUBROUTINE gfprep_write_inpxml

   SUBROUTINE gfprep_write_gfinp(prefix, geo)
      !Template of the gf_inp file; an existing file is not overwritten
      CHARACTER(LEN=*), INTENT(IN) :: prefix
      TYPE(t_layergeo), INTENT(IN) :: geo(:)

      LOGICAL :: l_exist
      INTEGER :: nl

      INQUIRE (FILE="gf_inp", EXIST=l_exist)
      IF (l_exist) THEN
         WRITE (*, *) "gf_inp exists and is not overwritten"
         RETURN
      END IF
      nl = SIZE(geo)
      OPEN (98, FILE="gf_inp", STATUS="new", ACTION="write")
      WRITE (98, "(a)") "!gf_inp template generated by gfprep"
      WRITE (98, "(a,i0,a,a,a)") "&LAYERS nlayers=", nl, ", prefix='", TRIM(prefix), "'"
      CALL priv_list("c1", geo(:)%z1)
      CALL priv_list("c2", geo(:)%z2)
      CALL priv_list("d", geo(:)%d)
      CALL priv_list("dt", geo(:)%dt)
      CALL priv_list("c", geo(:)%c)
      WRITE (98, "(a)") "/"
      WRITE (98, "(a)") "&MODE tmat=t, gmat=t /"
      !vacuum embedding at the outer planes of a film
      IF (geo(1)%vac(1) .OR. geo(nl)%vac(2)) &
         WRITE (98, "(a,l1,a,l1,a)") "&EMB addemb=T, surface=", geo(nl)%vac(2), ", vacleft=", geo(1)%vac(1), " /"
      WRITE (98, "(a)") "&SC iter=1 /"
      CLOSE (98)
   CONTAINS
      SUBROUTINE priv_list(name, val)
         CHARACTER(LEN=*), INTENT(IN) :: name
         REAL, INTENT(IN)             :: val(:)
         INTEGER :: i
         WRITE (98, "(3x,a,a)", advance="no") name, "="
         DO i = 1, SIZE(val)
            WRITE (98, "(f0.8)", advance="no") val(i)
            IF (i < SIZE(val)) WRITE (98, "(a)", advance="no") ", "
         END DO
         WRITE (98, "(a)") ","
      END SUBROUTINE priv_list
   END SUBROUTINE gfprep_write_gfinp


   SUBROUTINE gfprep_write_gfen(ef)
      !Template of the energy contour for the charge mode (gf_en.charge): a
      !semicircle in the complex plane from below the valence bands to the
      !Fermi energy of the bulk. Rename it to gf_en to use it.
      REAL, INTENT(IN) :: ef

      REAL, PARAMETER    :: width = 1.0 !start of the contour below E_F
      INTEGER, PARAMETER :: npts = 15   !2**n-1
      LOGICAL :: l_exist

      INQUIRE (FILE="gf_en.charge", EXIST=l_exist)
      IF (l_exist) THEN
         WRITE (*, *) "gf_en.charge exists and is not overwritten"
         RETURN
      END IF
      OPEN (98, FILE="gf_en.charge", STATUS="new", ACTION="write")
      WRITE (98, "(a,i10)") "c       ", npts
      WRITE (98, "(2f10.5)") ef - width, 0.0
      WRITE (98, "(2f10.5)") ef, 0.0
      CLOSE (98)
   END SUBROUTINE gfprep_write_gfen

   SUBROUTINE gfprep_write_potden(ilay, l, vtot_mt, vtot_pw, vcoul_pw, den_mt, den_pw, l_noco)
      !Writes the converted potential (gf_pot.hdf) and density (gf_cdn.hdf)
      INTEGER, INTENT(IN)               :: ilay
      TYPE(t_gfprep_struct), INTENT(IN) :: l
      REAL, INTENT(IN)                  :: vtot_mt(:, 0:, :, :), den_mt(:, 0:, :, :)
      COMPLEX, INTENT(IN)               :: vtot_pw(:, :), vcoul_pw(:), den_pw(:, :)
      LOGICAL, INTENT(IN)               :: l_noco

      TYPE(t_embinp) :: embinp
      INTEGER :: comm

#ifdef CPP_MPI
      comm = MPI_COMM_SELF
#else
      comm = 0
#endif
      CALL gf_wrtdop(GF_POTFILE, ilay, l%fi%input%jspins, embinp, l%fi%atoms, l%stars, l%sphhar, &
                     vtot_mt, vtot_pw, l_noco, comm)
      CALL gf_wrtcoul(GF_POTFILE, ilay, l%stars, vpw=vcoul_pw)
      CALL gf_wrtdop(GF_CDNFILE, ilay, l%fi%input%jspins, embinp, l%fi%atoms, l%stars, l%sphhar, &
                     den_mt, den_pw, l_noco, comm)
   END SUBROUTINE gfprep_write_potden

   SUBROUTINE gfprep_write_vacemb(side, delz, vz)
      !Writes the potential beyond a vacuum embedding plane to gf_pot.hdf
      INTEGER, INTENT(IN) :: side
      REAL, INTENT(IN)    :: delz, vz(:, :)

      INTEGER :: comm

#ifdef CPP_MPI
      comm = MPI_COMM_SELF
#else
      comm = 0
#endif
      CALL gf_iodop_writevacemb(side, delz, vz, comm)
      WRITE (oUnit, "(a,i1,a,i0,a,f8.4,a,2f12.6)") "gfprep: vacuum embedding potential side ", side, ": ", &
         SIZE(vz, 1), " points, delz=", delz, ", V(plane), V(end):", vz(1, 1), vz(SIZE(vz, 1), 1)
   END SUBROUTINE gfprep_write_vacemb

END MODULE m_gfprep_write
