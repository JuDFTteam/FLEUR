MODULE m_gfprep_write
   !Output of gfprep: the layer inp.xml files, the gf_inp template and the
   !layer potentials/densities in gf_pot.hdf/gf_cdn.hdf
#ifdef CPP_MPI
   USE mpi
#endif
   USE m_juDFT
   USE m_constants
   USE m_types_kpts
   USE m_types_forcetheo
   USE m_winpXML
   USE m_gf_types, ONLY: t_embinp
   USE m_gf_iodop, ONLY: gf_wrtdop, gf_wrtcoul, GF_POTFILE, GF_CDNFILE
   USE m_gfprep_inp, ONLY: t_layergeo
   USE m_gfprep_bulk, ONLY: t_gfprep_struct
   USE m_gfprep_layer, ONLY: t_gfprep_layer
   IMPLICIT NONE
   PRIVATE
   PUBLIC :: gfprep_write_inpxml, gfprep_write_gfinp, gfprep_write_potden

CONTAINS

   SUBROUTINE gfprep_write_inpxml(filename, b, lay, kpts)
      CHARACTER(LEN=*), INTENT(IN)      :: filename
      TYPE(t_gfprep_struct), INTENT(IN) :: b
      TYPE(t_gfprep_layer), INTENT(IN)  :: lay
      TYPE(t_kpts), INTENT(IN)          :: kpts

      TYPE(t_forcetheo) :: forcetheo
      TYPE(t_kpts)      :: kptsArray(1)
      CHARACTER(LEN=40) :: kptsSelection(3)

      kptsArray(1) = kpts
      kptsSelection = ""
      kptsSelection(1) = kpts%kptsName
      CALL w_inpXML(lay%atoms, lay%vacuum, lay%input, b%stars, b%fi%sliceplot, forcetheo, b%fi%banddos, &
                    b%fi%dfpt, lay%cell, lay%sym, b%xcpot, b%fi%noco, b%fi%mpinp, b%fi%hybinp, kptsArray, &
                    kptsSelection, lay%enpara, b%fi%gfinp, b%fi%hub1inp, .FALSE., [.TRUE., .TRUE., .TRUE., .TRUE.], &
                    filename=filename, add_filename="")
   END SUBROUTINE gfprep_write_inpxml

   SUBROUTINE gfprep_write_gfinp(prefix, geo)
      !Template of the gf_inp file; an existing file is not overwritten
      CHARACTER(LEN=*), INTENT(IN) :: prefix
      TYPE(t_layergeo), INTENT(IN) :: geo(:)

      LOGICAL :: l_exist
      INTEGER :: nl

      INQUIRE (FILE="gf_inp", EXIST=l_exist)
      IF (l_exist) THEN
         WRITE (*, *) "gf_inp exists and is not overwritten"
         RETURN
      END IF
      nl = SIZE(geo)
      OPEN (98, FILE="gf_inp", STATUS="new", ACTION="write")
      WRITE (98, "(a)") "!gf_inp template generated by gfprep"
      WRITE (98, "(a,i0,a,a,a)") "&LAYERS nlayers=", nl, ", prefix='", TRIM(prefix), "'"
      CALL priv_list("c1", geo(:)%z1)
      CALL priv_list("c2", geo(:)%z2)
      CALL priv_list("d", geo(:)%d)
      CALL priv_list("dt", geo(:)%dt)
      CALL priv_list("c", geo(:)%c)
      WRITE (98, "(a)") "/"
      WRITE (98, "(a)") "&MODE tmat=t, gmat=t /"
      WRITE (98, "(a)") "&SC iter=1 /"
      CLOSE (98)
   CONTAINS
      SUBROUTINE priv_list(name, val)
         CHARACTER(LEN=*), INTENT(IN) :: name
         REAL, INTENT(IN)             :: val(:)
         INTEGER :: i
         WRITE (98, "(3x,a,a)", advance="no") name, "="
         DO i = 1, SIZE(val)
            WRITE (98, "(f0.8)", advance="no") val(i)
            IF (i < SIZE(val)) WRITE (98, "(a)", advance="no") ", "
         END DO
         WRITE (98, "(a)") ","
      END SUBROUTINE priv_list
   END SUBROUTINE gfprep_write_gfinp

   SUBROUTINE gfprep_write_potden(ilay, l, vtot_mt, vtot_pw, vcoul_pw, den_mt, den_pw)
      !Writes the converted potential (gf_pot.hdf) and density (gf_cdn.hdf)
      INTEGER, INTENT(IN)               :: ilay
      TYPE(t_gfprep_struct), INTENT(IN) :: l
      REAL, INTENT(IN)                  :: vtot_mt(:, 0:, :, :), den_mt(:, 0:, :, :)
      COMPLEX, INTENT(IN)               :: vtot_pw(:, :), vcoul_pw(:), den_pw(:, :)

      TYPE(t_embinp) :: embinp
      INTEGER :: comm

#ifdef CPP_MPI
      comm = MPI_COMM_SELF
#else
      comm = 0
#endif
      CALL gf_wrtdop(GF_POTFILE, ilay, l%fi%input%jspins, embinp, l%fi%atoms, l%stars, l%sphhar, &
                     vtot_mt, vtot_pw, .FALSE., comm)
      CALL gf_wrtcoul(GF_POTFILE, ilay, l%stars, vpw=vcoul_pw)
      CALL gf_wrtdop(GF_CDNFILE, ilay, l%fi%input%jspins, embinp, l%fi%atoms, l%stars, l%sphhar, &
                     den_mt, den_pw, .FALSE., comm)
   END SUBROUTINE gfprep_write_potden

END MODULE m_gfprep_write
