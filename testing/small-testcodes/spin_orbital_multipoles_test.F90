      WRITE(*,'(A,I3,2(A,2ES20.11),A,ES14.6)') "w415 t=", t, " expected=", golden_w(4,1,5,t), &
         " actual=", w(4,1,5,t), " error=", ABS(w(4,1,5,t)-golden_w(4,1,5,t))
   END DO
   CALL check_bound("frozen independent w(4,1,5,t) fixture", max_golden, tolerance, failures)

   nl4 = 24.0/SQRT(362880.0)
   ns1 = 1.0/SQRT(6.0)
   bracket415 = -5.0/SQRT(495.0)
   prefactor415 = parity_test(4+1+l)/(nl4*ns1*bracket415)
   CALL check_real("n_l4", nl4, 1.0/SQRT(630.0), tolerance, failures)
   CALL check_real("n_s1", ns1, 1.0/SQRT(6.0), tolerance, failures)
   CALL check_real("[4 1 5]", bracket415, -5.0/SQRT(495.0), tolerance, failures)
   CALL check_real("validated w415 source-form prefactor", prefactor415, &
                   2.7357631476427190e+02, tolerance, failures)

   WRITE(*,'(A,ES14.6)') "Maximum analytic round-trip error: ", max_roundtrip
   WRITE(*,'(A,ES14.6)') "Maximum relative round-trip error: ", max_roundtrip_relative
   WRITE(*,'(A,ES14.6)') "Maximum Hermiticity-relation error: ", max_hermiticity
   WRITE(*,'(A,ES14.6)') "Maximum tensor scalar-product error: ", max_scalar_error
   WRITE(*,'(A,ES14.6)') "Maximum spin-unpolarized p=1 magnitude: ", max_unpolarized
   WRITE(*,'(A,ES14.6)') "Maximum complete frozen l=2 forward error: ", max_complete_golden
   WRITE(*,'(A,ES14.6)') "Maximum d-spin adapter golden error: ", max_adapter_golden
   WRITE(*,'(A,ES14.6)') "Maximum d-spin adapter direct-core error: ", max_adapter_direct
   WRITE(*,'(A,ES14.6)') "Maximum frozen-tensor inverse error: ", max_frozen_inverse
   WRITE(*,'(A,ES14.6)') "Maximum frozen w415 error: ", max_golden
   CALL expect_api_failure("--api-failure-negative-l", failures)
   CALL expect_api_failure("--api-failure-large-l", failures)
   CALL expect_api_failure("--api-failure-rho-shape", failures)
   CALL expect_api_failure("--api-failure-w-shape", failures)
   CALL expect_api_failure("--adapter-api-failure-rho-shape", failures)
   CALL expect_api_failure("--adapter-api-failure-w-shape", failures)
   IF (failures > 0) THEN
      WRITE(*,'(A,I0)') "SPIN-ORBITAL MULTIPOLES TEST: FAIL, failures = ", failures
      ERROR STOP 1
   END IF
   WRITE(*,'(A)') "SPIN-ORBITAL MULTIPOLES TEST: PASS"

