      REAL, INTENT(IN) :: value, expected, bound
      INTEGER, INTENT(INOUT) :: failures

      CALL check_bound(label, ABS(value-expected), bound, failures)
   END SUBROUTINE check_real

   SUBROUTINE check_integer(label, value, expected, failures)
