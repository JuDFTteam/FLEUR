      INTEGER, INTENT(INOUT) :: failures

      IF (value > bound) THEN
         failures = failures+1
         WRITE(*,'(A,2ES18.8)') "FAIL "//TRIM(label)//": ", value, bound
      ELSE
         WRITE(*,'(A,ES14.6)') "PASS "//TRIM(label)//": ", value
      END IF
   END SUBROUTINE check_bound

   SUBROUTINE check_separation(label,value,failures)
      CHARACTER(LEN=*), INTENT(IN) :: label
      REAL, INTENT(IN) :: value
      INTEGER, INTENT(INOUT) :: failures

      IF (value <= 1000.0*tolerance) THEN
         failures = failures+1
         WRITE(*,'(A,ES18.8)') "FAIL "//TRIM(label)//": ",value
      ELSE
         WRITE(*,'(A,ES14.6)') "PASS "//TRIM(label)//": ",value
      END IF
   END SUBROUTINE check_separation

   SUBROUTINE check_complex(label, value, expected, bound, failures)
      CHARACTER(LEN=*), INTENT(IN) :: label
      COMPLEX, INTENT(IN) :: value, expected
      REAL, INTENT(IN) :: bound
      INTEGER, INTENT(INOUT) :: failures

