   WRITE(*,'(A,4(I0,1X))') "Maximum adapter-error location (k,p,r,t): ", &
                           adapter_k, adapter_p, adapter_r, adapter_t
   CALL check_bound("d-spin adapter agrees with direct core", max_adapter_direct, tolerance, failures)
   CALL check_integer("d-spin adapter invalid dense entries", adapter_invalid_nonzero, 0, failures)
   CALL test_adapter_convention_controls(rho,golden_w,failures)

   CALL spin_orbital_multipoles_to_density(l, golden_w, reconstructed)
   max_frozen_inverse = MAXVAL(ABS(reconstructed-rho))
   CALL check_bound("frozen independent l=2 tensor analytic inverse", max_frozen_inverse, tolerance, failures)

   max_golden = 0.0
   DO t = -5, 5
