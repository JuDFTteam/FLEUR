   SUBROUTINE test_general_l(ll, failures)
      INTEGER, INTENT(IN) :: ll
      INTEGER, INTENT(INOUT) :: failures

      COMPLEX, ALLOCATABLE :: local_rho(:,:,:,:), local_w(:,:,:,:), local_reconstructed(:,:,:,:)
      COMPLEX :: upper_value
      REAL :: roundtrip_error, hermiticity_error
      INTEGER :: local_dim, local_count, local_invalid
      INTEGER :: mm, mmp, ss, ssp, row, col, kk, pp, rr, tt
      CHARACTER(LEN=80) :: label

      local_dim = 2*(2*ll+1)
      ALLOCATE(local_rho(-ll:ll,2,-ll:ll,2))
      ALLOCATE(local_reconstructed(-ll:ll,2,-ll:ll,2))
      ALLOCATE(local_w(0:2*ll,0:1,0:2*ll+1,-(2*ll+1):2*ll+1))

      DO mm = -ll, ll
         DO ss = 1, 2
            row = 2*(mm+ll)+ss
            DO mmp = -ll, ll
               DO ssp = 1, 2
                  col = 2*(mmp+ll)+ssp
                  IF (row == col) THEN
                     local_rho(mm,ss,mmp,ssp) = 0.19*row+0.005*row*row
                  ELSE IF (row < col) THEN
                     local_rho(mm,ss,mmp,ssp) = CMPLX(0.014*(row+2*col)/(1+col-row), &
                                                              0.006*(2*row-col)/(1+col-row))
                  ELSE
                     upper_value = CMPLX(0.014*(col+2*row)/(1+row-col), &
                                         0.006*(2*col-row)/(1+row-col))
                     local_rho(mm,ss,mmp,ssp) = CONJG(upper_value)
                  END IF
               END DO
            END DO
         END DO
      END DO

      CALL spin_orbital_density_to_multipoles(ll, local_rho, local_w)
      local_count = 0
      local_invalid = 0
      hermiticity_error = 0.0
      DO kk = 0, 2*ll
         DO pp = 0, 1
            DO rr = 0, 2*ll+1
               DO tt = -(2*ll+1), 2*ll+1
                  IF (valid_component(kk,pp,rr,tt)) THEN
                     local_count = local_count+1
                     hermiticity_error = MAX(hermiticity_error, &
                        ABS(CONJG(local_w(kk,pp,rr,tt))-parity_test(tt)*local_w(kk,pp,rr,-tt)))
                  ELSE IF (ABS(local_w(kk,pp,rr,tt)) > 0.0) THEN
                     local_invalid = local_invalid+1
                  END IF
               END DO
            END DO
         END DO
      END DO
      WRITE(label,'("l=",I0," coupled component count")') ll
      CALL check_integer(TRIM(label), local_count, 4*(2*ll+1)**2, failures)
      WRITE(label,'("l=",I0," invalid dense entries")') ll
      CALL check_integer(TRIM(label), local_invalid, 0, failures)
      IF (ll == 0) CALL check_integer("l=0 has only charge plus three spin components", local_count, 4, failures)

      CALL spin_orbital_multipoles_to_density(ll, local_w, local_reconstructed)
      roundtrip_error = MAXVAL(ABS(local_reconstructed-local_rho))
      WRITE(label,'("l=",I0," deterministic Hermitian round trip")') ll
      CALL check_bound(TRIM(label), roundtrip_error, tolerance, failures)
      WRITE(label,'("l=",I0," Hermiticity relation")') ll
      CALL check_bound(TRIM(label), hermiticity_error, tolerance, failures)
      WRITE(*,'(A,I0,2(A,ES14.6))') "General-l summary l=", ll, &
         ": round trip = ", roundtrip_error, ", Hermiticity = ", hermiticity_error
   END SUBROUTINE test_general_l

   SUBROUTINE expect_api_failure(argument, failures)
      CHARACTER(LEN=*), INTENT(IN) :: argument
      INTEGER, INTENT(INOUT) :: failures

      CHARACTER(LEN=1024) :: executable, command
      INTEGER :: command_status, exit_status

      CALL GET_COMMAND_ARGUMENT(0, executable)
      command = '"'//TRIM(executable)//'" '//TRIM(argument)
      CALL EXECUTE_COMMAND_LINE(TRIM(command), WAIT=.TRUE., EXITSTAT=exit_status, CMDSTAT=command_status)
      IF (command_status /= 0 .OR. exit_status == 0) THEN
         failures = failures+1
         WRITE(*,'(A,2I8)') "FAIL expected API rejection "//TRIM(argument)//": ", &
                            command_status, exit_status
      ELSE
         WRITE(*,'(A,I0)') "PASS expected API rejection "//TRIM(argument)//": exit status ", exit_status
      END IF
   END SUBROUTINE expect_api_failure

   SUBROUTINE run_api_failure_case(argument)
      CHARACTER(LEN=*), INTENT(IN) :: argument

      COMPLEX, ALLOCATABLE :: bad_rho(:,:,:,:), bad_w(:,:,:,:)

      SELECT CASE (argument)
      CASE ("--api-failure-negative-l")
         ALLOCATE(bad_rho(1,2,1,2), bad_w(1,2,2,3))
         CALL spin_orbital_density_to_multipoles(-1, bad_rho, bad_w)
      CASE ("--api-failure-large-l")
         ALLOCATE(bad_rho(1,2,1,2), bad_w(1,2,2,3))
         CALL spin_orbital_multipoles_to_density(4, bad_w, bad_rho)
      CASE ("--api-failure-rho-shape")
         ALLOCATE(bad_rho(4,2,5,2), bad_w(5,2,6,11))
         CALL spin_orbital_density_to_multipoles(2, bad_rho, bad_w)
      CASE ("--api-failure-w-shape")
         ALLOCATE(bad_rho(5,2,5,2), bad_w(5,2,5,11))
         CALL spin_orbital_multipoles_to_density(2, bad_w, bad_rho)
      CASE ("--adapter-api-failure-rho-shape")
         ALLOCATE(bad_rho(4,2,5,2), bad_w(5,2,6,11))
         CALL local_d_spin_density_to_multipoles(bad_rho,bad_w)
      CASE ("--adapter-api-failure-w-shape")
         ALLOCATE(bad_rho(5,2,5,2), bad_w(5,2,5,11))
         CALL local_d_spin_density_to_multipoles(bad_rho,bad_w)
      CASE DEFAULT
         ERROR STOP "Unknown API-failure test"
      END SELECT
   END SUBROUTINE run_api_failure_case

   SUBROUTINE test_adapter_convention_controls(reference_rho,reference_w,failures)
      COMPLEX, INTENT(IN) :: reference_rho(-l:l,2,-l:l,2)
      COMPLEX, INTENT(IN) :: reference_w(0:2*l,0:1,0:2*l+1,-(2*l+1):2*l+1)
      INTEGER, INTENT(INOUT) :: failures

      COMPLEX :: wrong_rho(-l:l,2,-l:l,2), wrong_w(0:2*l,0:1,0:2*l+1,-(2*l+1):2*l+1)
      COMPLEX :: general_rho(-l:l,2,-l:l,2), general_w(0:2*l,0:1,0:2*l+1,-(2*l+1):2*l+1)
      COMPLEX :: general_matrix(dim,dim)
      REAL :: orbital_partial_transpose_difference, spin_swap_difference, conjugation_difference
      REAL :: full_adjoint_difference
      INTEGER :: mm, mmp, ss, ssp

      DO mm = -l, l
         DO ss = 1, 2
            DO mmp = -l, l
               DO ssp = 1, 2
                  wrong_rho(mm,ss,mmp,ssp) = reference_rho(mmp,ss,mm,ssp)
               END DO
            END DO
         END DO
      END DO
      CALL local_d_spin_density_to_multipoles(wrong_rho,wrong_w)
      orbital_partial_transpose_difference = MAXVAL(ABS(wrong_w-reference_w))
      CALL check_separation("orbital partial transpose changes frozen tensor", &
                            orbital_partial_transpose_difference,failures)

      DO mm = -l, l
         DO ss = 1, 2
            DO mmp = -l, l
               DO ssp = 1, 2
                  wrong_rho(mm,ss,mmp,ssp) = reference_rho(mm,3-ss,mmp,3-ssp)
               END DO
            END DO
         END DO
      END DO
      CALL local_d_spin_density_to_multipoles(wrong_rho,wrong_w)
      spin_swap_difference = MAXVAL(ABS(wrong_w-reference_w))
      CALL check_separation("swapped spin indices change frozen tensor",spin_swap_difference,failures)

      wrong_rho = CONJG(reference_rho)
      CALL local_d_spin_density_to_multipoles(wrong_rho,wrong_w)
      conjugation_difference = MAXVAL(ABS(wrong_w-reference_w))
      CALL check_separation("complex conjugation changes frozen tensor",conjugation_difference,failures)

      CALL initialize_general_matrix(general_matrix)
      CALL matrix_to_density(general_matrix,general_rho)
      CALL local_d_spin_density_to_multipoles(general_rho,general_w)
      DO mm = -l, l
         DO ss = 1, 2
            DO mmp = -l, l
               DO ssp = 1, 2
                  wrong_rho(mm,ss,mmp,ssp) = CONJG(general_rho(mmp,ssp,mm,ss))
               END DO
            END DO
         END DO
      END DO
      CALL local_d_spin_density_to_multipoles(wrong_rho,wrong_w)
      full_adjoint_difference = MAXVAL(ABS(wrong_w-general_w))
      CALL check_separation("full adjoint is detectable for general density",full_adjoint_difference,failures)

      WRITE(*,'(A,ES14.6)') "Orbital-partial-transpose tensor separation: ", &
                            orbital_partial_transpose_difference
      WRITE(*,'(A,ES14.6)') "Spin-swap tensor separation: ",spin_swap_difference
      WRITE(*,'(A,ES14.6)') "Complex-conjugation tensor separation: ",conjugation_difference
      WRITE(*,'(A,ES14.6)') "General-density full-adjoint tensor separation: ",full_adjoint_difference
   END SUBROUTINE test_adapter_convention_controls

   SUBROUTINE check_roundtrip(input, multipoles, output, maximum, maximum_relative, failures)
      COMPLEX, INTENT(IN) :: input(-l:l,2,-l:l,2)
      COMPLEX, INTENT(OUT) :: multipoles(0:2*l,0:1,0:2*l+1,-(2*l+1):2*l+1)
      COMPLEX, INTENT(OUT) :: output(-l:l,2,-l:l,2)
      REAL, INTENT(INOUT) :: maximum, maximum_relative
      INTEGER, INTENT(INOUT) :: failures

      REAL :: local_error

      CALL spin_orbital_density_to_multipoles(l, input, multipoles)
      CALL spin_orbital_multipoles_to_density(l, multipoles, output)
      local_error = MAXVAL(ABS(output-input))
      maximum = MAX(maximum, local_error)
      maximum_relative = MAX(maximum_relative, local_error/MAX(MAXVAL(ABS(input)), TINY(1.0)))
      IF (local_error > tolerance) failures = failures + 1
   END SUBROUTINE check_roundtrip

   SUBROUTINE test_spin_state(label, state, failures)
      CHARACTER(LEN=*), INTENT(IN) :: label
      COMPLEX, INTENT(IN) :: state(2)
      INTEGER, INTENT(INOUT) :: failures

      COMPLEX :: local_rho(-l:l,2,-l:l,2)
      COMPLEX :: local_w(0:2*l,0:1,0:2*l+1,-(2*l+1):2*l+1)
      COMPLEX :: spherical(-1:1)
      INTEGER :: sa, sb, y

      local_rho = CMPLX(0.0,0.0)
      DO sa = 1, 2
         DO sb = 1, 2
            local_rho(0,sa,0,sb) = state(sa)*CONJG(state(sb))
         END DO
      END DO
      spherical(0) = ABS(state(1))**2-ABS(state(2))**2
      spherical(1) = -SQRT(2.0)*CONJG(state(1))*state(2)
      spherical(-1) = SQRT(2.0)*CONJG(state(2))*state(1)
      CALL spin_orbital_density_to_multipoles(l, local_rho, local_w)
      CALL check_complex(label//" trace", local_w(0,0,0,0), CMPLX(1.0,0.0), tolerance, failures)
      DO y = -1, 1
         CALL check_complex(label//" w011=-w01", local_w(0,1,1,y), -spherical(y), &
                            tolerance, failures)
      END DO
   END SUBROUTINE test_spin_state

   SUBROUTINE initialize_general_matrix(output)
      COMPLEX, INTENT(OUT) :: output(dim,dim)
      INTEGER :: row, col

      DO row = 1, dim
         DO col = 1, dim
            output(row,col) = CMPLX(0.031*row-0.017*col+0.002*row*col, &
                                    0.019*row+0.023*col-0.001*row*col)
         END DO
      END DO
   END SUBROUTINE initialize_general_matrix

   SUBROUTINE initialize_hermitian_matrix(output)
      COMPLEX, INTENT(OUT) :: output(dim,dim)
      INTEGER :: row, col

      output = CMPLX(0.0,0.0)
      DO row = 1, dim
         output(row,row) = 0.21*row+0.007*row*row
         DO col = row+1, dim
            output(row,col) = CMPLX(0.012*(row+col)/(1+col-row), &
                                             0.008*(2*row-col)/(1+col-row))
            output(col,row) = CONJG(output(row,col))
         END DO
      END DO
   END SUBROUTINE initialize_hermitian_matrix

   SUBROUTINE initialize_golden_density(output)
      COMPLEX, INTENT(OUT) :: output(dim,dim)
      INTEGER :: row, col

      output = CMPLX(0.0,0.0)
      DO row = 1, dim
         output(row,row) = 0.17*row+0.011*row*row
         DO col = row+1, dim
            output(row,col) = CMPLX(0.013*(row+2*col)/(1+col-row), &
                                    0.009*(2*row-col)/(1+col-row))
            output(col,row) = CONJG(output(row,col))
         END DO
      END DO
   END SUBROUTINE initialize_golden_density

   SUBROUTINE initialize_orbital_hermitian(output)
      COMPLEX, INTENT(OUT) :: output(5,5)
      INTEGER :: row, col

      output = CMPLX(0.0,0.0)
      DO row = 1, 5
         output(row,row) = 0.3+0.1*row
         DO col = row+1, 5
            output(row,col) = CMPLX(0.02*(row+col),0.015*(row-col))
            output(col,row) = CONJG(output(row,col))
         END DO
      END DO
   END SUBROUTINE initialize_orbital_hermitian

   SUBROUTINE matrix_to_density(input, output)
      COMPLEX, INTENT(IN) :: input(dim,dim)
      COMPLEX, INTENT(OUT) :: output(-l:l,2,-l:l,2)
      INTEGER :: row, col, mm, mmp, ss, ssp

      DO mm = -l, l
         DO ss = 1, 2
            row = 2*(mm+l)+ss
            DO mmp = -l, l
               DO ssp = 1, 2
                  col = 2*(mmp+l)+ssp
                  output(mm,ss,mmp,ssp) = input(row,col)
               END DO
            END DO
         END DO
      END DO
   END SUBROUTINE matrix_to_density

   SUBROUTINE set_flat_density_element(output, row, col, value)
      COMPLEX, INTENT(INOUT) :: output(-l:l,2,-l:l,2)
      INTEGER, INTENT(IN) :: row, col
      COMPLEX, INTENT(IN) :: value
      INTEGER :: mm, mmp, ss, ssp

      mm = (row-1)/2-l
      ss = MOD(row-1,2)+1
      mmp = (col-1)/2-l
      ssp = MOD(col-1,2)+1
      output(mm,ss,mmp,ssp) = value
   END SUBROUTINE set_flat_density_element

   COMPLEX FUNCTION trace_density(input)
      COMPLEX, INTENT(IN) :: input(-l:l,2,-l:l,2)
      INTEGER :: mm, ss

      trace_density = CMPLX(0.0,0.0)
      DO mm = -l, l
         DO ss = 1, 2
            trace_density = trace_density+input(mm,ss,mm,ss)
         END DO
      END DO
   END FUNCTION trace_density

   LOGICAL FUNCTION valid_component(kk, pp, rr, tt)
      INTEGER, INTENT(IN) :: kk, pp, rr, tt

      valid_component = rr >= ABS(kk-pp) .AND. rr <= kk+pp .AND. ABS(tt) <= rr
   END FUNCTION valid_component

   REAL FUNCTION parity_test(n)
      INTEGER, INTENT(IN) :: n

      parity_test = MERGE(1.0,-1.0,MOD(ABS(n),2)==0)
   END FUNCTION parity_test

   SUBROUTINE check_bound(label, value, bound, failures)
      CHARACTER(LEN=*), INTENT(IN) :: label
